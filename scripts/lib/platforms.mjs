// Platform discovery and code generation, shared by the build and the tests.
import { readdir, readFile, access } from "node:fs/promises";
import path from "node:path";

/** Files every content script loads before and after the platform's own code. */
export const CONTENT_CORE_BEFORE = [
  "core/api.js",
  "core/registry.js",
  "core/platforms.generated.js",
  "core/storage.js",
  "core/content-core.js",
  "core/player-controls.js",
];
/** Stylesheets every content script loads before the platform's own. */
export const CONTENT_CSS_BEFORE = ["core/player-controls.css"];
export const CONTENT_CORE_AFTER = ["core/content-start.js"];

/** Files loaded by the background (event page / service worker). */
export const BACKGROUND_FILES = [
  "core/api.js",
  "core/registry.js",
  "core/platforms.generated.js",
  "core/storage.js",
  "background/background.js",
];

const exists = (p) => access(p).then(() => true, () => false);

/** Reads and validates src/platforms/<id>/platform.json for every platform. */
export async function discoverPlatforms(srcDir) {
  const dir = path.join(srcDir, "platforms");
  const entries = (await readdir(dir, { withFileTypes: true })).filter((e) => e.isDirectory());
  const platforms = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const base = path.join(dir, entry.name);
    const meta = JSON.parse(await readFile(path.join(base, "platform.json"), "utf8"));
    validate(meta, entry.name);
    const js = [...CONTENT_CORE_BEFORE];
    if (await exists(path.join(base, "content.js"))) js.push(`platforms/${meta.id}/content.js`);
    js.push(...CONTENT_CORE_AFTER);
    const css = [...CONTENT_CSS_BEFORE];
    if (await exists(path.join(base, "content.css"))) css.push(`platforms/${meta.id}/content.css`);
    platforms.push({ ...meta, contentFiles: { js, css } });
  }
  return platforms.sort((a, b) => (a.order ?? 1000) - (b.order ?? 1000) || a.id.localeCompare(b.id));
}

export function validate(meta, folder) {
  const fail = (msg) => {
    throw new Error(`platforms/${folder}/platform.json: ${msg}`);
  };
  if (meta.id !== folder) fail(`id "${meta.id}" must equal the folder name`);
  if (!/^[a-z][a-z0-9]*$/.test(meta.id)) fail("id must be lowercase letters and digits");
  if (typeof meta.label !== "string" || !meta.label) fail("label missing");
  if (!Array.isArray(meta.matches) || !meta.matches.length) fail("matches missing");
  if (!["required", "optional"].includes(meta.hostAccess)) fail('hostAccess must be "required" or "optional"');
  if (meta.order !== undefined && !Number.isInteger(meta.order)) fail("order must be an integer");
  if (typeof meta.contentScript !== "boolean") fail("contentScript must be true or false");
  if (!Array.isArray(meta.options)) fail("options missing");
  const keys = new Set();
  for (const o of meta.options) {
    if (!/^[a-z][A-Za-z0-9]*$/.test(o.key || "")) fail(`option key "${o.key}" must be camelCase`);
    if (o.key === "enabled") fail('option key "enabled" is reserved');
    if (keys.has(o.key)) fail(`duplicate option key "${o.key}"`);
    keys.add(o.key);
    if (typeof o.label !== "string" || !o.label) fail(`option "${o.key}" has no label`);
    if (typeof o.default !== "boolean") fail(`option "${o.key}" default must be boolean`);
  }
}

/** Source of core/platforms.generated.js. */
export function generateRegistrySource(platforms) {
  return [
    "/* Generated by scripts/build.mjs from src/platforms/<id>/platform.json. Do not edit. */",
    '"use strict";',
    "",
    `globalThis.NoSpoiler.registerPlatforms(${JSON.stringify(platforms, null, 2)});`,
    "",
  ].join("\n");
}
