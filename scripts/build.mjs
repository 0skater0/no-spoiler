// Builds dist/firefox and dist/chrome from src/.
// Usage: node scripts/build.mjs [firefox|chrome]...
import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BACKGROUND_FILES, discoverPlatforms, generateRegistrySource } from "./lib/platforms.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "src");
export const BROWSERS = ["firefox", "chrome"];

export const GECKO_ID = "{d27fe5e6-f507-492e-b030-1a17debff539}";
export const MIN_FIREFOX = "140.0";
export const MIN_CHROME = "120";
export const CHROME_SHORTCUT = { default: "Alt+Shift+U", mac: "Command+Shift+U" };

function description(platforms) {
  const names = platforms.map((p) => p.label);
  const list = names.length > 1 ? `${names.slice(0, -1).join(", ")} and ${names.at(-1)}` : names[0];
  return `Hide spoilers on ${list}: video time, progress bars, durations, comments, chat replay, recommendations and more.`;
}

export function createManifest(browser, { base, version, platforms }) {
  const required = platforms.filter((p) => p.hostAccess === "required");
  const optional = platforms.filter((p) => p.hostAccess === "optional");
  const m = {
    ...structuredClone(base),
    version,
    description: description(platforms),
    host_permissions: required.flatMap((p) => p.matches),
  };
  if (optional.length) m.optional_host_permissions = optional.flatMap((p) => p.matches);

  // Platforms with required access get a static content script; optional ones
  // are registered at runtime once access is granted (background.js).
  const staticScripts = required.filter((p) => p.contentScript);
  if (staticScripts.length) {
    m.content_scripts = staticScripts.map((p) => ({
      matches: p.matches,
      js: p.contentFiles.js,
      css: p.contentFiles.css,
      run_at: "document_start",
    }));
  }

  if (browser === "firefox") {
    m.background = { scripts: BACKGROUND_FILES };
    m.browser_specific_settings = {
      gecko: {
        id: GECKO_ID,
        strict_min_version: MIN_FIREFOX,
        data_collection_permissions: { required: ["none"] },
      },
    };
  } else if (browser === "chrome") {
    m.background = { service_worker: "background/service-worker.js" };
    // Chrome rejects Ctrl+Alt shortcuts (AltGr conflicts) and then refuses to
    // load the whole extension. Firefox keeps the shortcut of the 0.9.x version.
    m.commands["toggle-addon"].suggested_key = CHROME_SHORTCUT;
    m.minimum_chrome_version = MIN_CHROME;
  } else {
    throw new Error(`Unknown browser: ${browser}`);
  }
  return m;
}

export async function build(browser, outRoot = path.join(ROOT, "dist")) {
  const pkg = JSON.parse(await readFile(path.join(ROOT, "package.json"), "utf8"));
  const base = JSON.parse(await readFile(path.join(ROOT, "scripts", "manifest.base.json"), "utf8"));
  const platforms = await discoverPlatforms(SRC);
  const out = path.join(outRoot, browser);

  await rm(out, { recursive: true, force: true });
  await mkdir(out, { recursive: true });
  await cp(SRC, out, {
    recursive: true,
    // platform.json is compiled into core/platforms.generated.js
    filter: (src) => path.basename(src) !== "platform.json",
  });

  await writeFile(path.join(out, "core", "platforms.generated.js"), generateRegistrySource(platforms));

  if (browser === "chrome") {
    const imports = BACKGROUND_FILES.map((f) => `  "/${f}",`).join("\n");
    await writeFile(
      path.join(out, "background", "service-worker.js"),
      `/* Generated by scripts/build.mjs. Chrome service worker entry. */\n"use strict";\n\nimportScripts(\n${imports}\n);\n`,
    );
  }

  const manifest = createManifest(browser, { base, version: pkg.version, platforms });
  await writeFile(path.join(out, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  return { out, manifest };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const targets = process.argv.slice(2).length ? process.argv.slice(2) : BROWSERS;
  for (const browser of targets) {
    const { out } = await build(browser);
    console.log(`Built ${path.relative(ROOT, out)}`);
  }
}
